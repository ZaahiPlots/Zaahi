// ZAAHI Feasibility v6.1 — shared jsPDF primitives.
//
// One set of colours, margins and table helpers for both the feasibility
// report (pdf.ts) and the study-comparison export, so the two read as one
// family of documents. Client-only (jsPDF).
//
// ASCII only in anything passed to these helpers: jsPDF's built-in Helvetica
// and Times are WinANSI and render "≥", "Δ", "→" as garbage. `ascii()` maps
// the characters the model emits.

import { jsPDF } from 'jspdf';

export type RGB = [number, number, number];

export const PDF_COLORS = {
  gold: [200, 169, 110] as RGB,
  goldDark: [148, 119, 71] as RGB,
  dark: [26, 26, 46] as RGB,
  gray: [107, 114, 128] as RGB,
  cream: [251, 248, 240] as RGB,
  green: [45, 106, 79] as RGB,
  amber: [230, 126, 34] as RGB,
  red: [230, 57, 70] as RGB,
  line: [229, 231, 235] as RGB,
  white: [255, 255, 255] as RGB,
};

export function ascii(s: string): string {
  return s
    .replace(/[–—]/g, '-')
    .replace(/[·•]/g, '-')
    .replace(/→/g, '->')
    .replace(/≥/g, '>=')
    .replace(/≤/g, '<=')
    .replace(/×/g, 'x')
    .replace(/÷/g, '/')
    .replace(/−/g, '-')
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/…/g, '...')
    .replace(/[^\x20-\x7E\n]/g, '');
}

export function hexToRgb(hex: string): RGB {
  const h = hex.replace('#', '');
  return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16)];
}

export interface PdfKit {
  doc: jsPDF;
  W: number;
  H: number;
  M: number;
  /** Current baseline. Read and write freely. */
  y: number;
  newPage(): void;
  /** Break to a new page unless `need` mm are left. */
  ensure(need: number): void;
  gap(mm?: number): void;
  sectionTitle(t: string): void;
  subhead(t: string): void;
  /** Wrapped paragraph. Returns nothing; advances y. */
  para(t: string, o?: { size?: number; color?: RGB; italic?: boolean; bold?: boolean; indent?: number; width?: number }): void;
  /** Label left, value right. */
  row(label: string, value: string, o?: { tint?: boolean; bold?: boolean; valueColor?: RGB; note?: string }): void;
  /**
   * A table. `widths` are fractions of the usable width and should sum to 1;
   * the first column is left-aligned, the rest right-aligned unless `align` says otherwise.
   */
  table(o: {
    head: string[];
    rows: string[][];
    widths: number[];
    align?: Array<'left' | 'right' | 'center'>;
    size?: number;
    /** Per-cell colour override, e.g. to highlight the best value in a row. */
    cellColor?: (row: number, col: number) => RGB | undefined;
    boldCell?: (row: number, col: number) => boolean;
    boldRows?: number[];
  }): void;
  /** Stamp "generated by" + page numbers on every page. Call once, last. */
  finish(footerLeft: string): void;
}

export function createPdfKit(orientation: 'portrait' | 'landscape' = 'portrait'): PdfKit {
  const doc = new jsPDF({ unit: 'mm', format: 'a4', orientation });
  const W = orientation === 'portrait' ? 210 : 297;
  const H = orientation === 'portrait' ? 297 : 210;
  const M = 15;
  const C = PDF_COLORS;
  let pages = 0;

  const kit: PdfKit = {
    doc,
    W,
    H,
    M,
    y: 0,
    newPage() {
      if (pages > 0) doc.addPage();
      pages += 1;
      doc.setFillColor(...C.gold);
      doc.rect(0, 0, W, 4, 'F');
      kit.y = 16;
    },
    ensure(need) {
      if (kit.y + need > H - 16) kit.newPage();
    },
    gap(mm = 6) {
      kit.y += mm;
    },
    sectionTitle(t) {
      kit.ensure(22);
      doc.setFontSize(10.5);
      doc.setTextColor(...C.goldDark);
      doc.setFont('times', 'bold');
      doc.text(ascii(t).toUpperCase(), M, kit.y);
      doc.setDrawColor(...C.gold);
      doc.setLineWidth(0.3);
      doc.line(M, kit.y + 1.6, W - M, kit.y + 1.6);
      kit.y += 8;
    },
    subhead(t) {
      kit.y += 2;
      kit.ensure(14);
      doc.setFontSize(9.5);
      doc.setTextColor(...C.goldDark);
      doc.setFont('times', 'bold');
      doc.text(ascii(t), M, kit.y);
      kit.y += 5.5;
    },
    para(t, o) {
      const size = o?.size ?? 9;
      const indent = o?.indent ?? 0;
      const width = o?.width ?? W - 2 * M - indent;
      doc.setFontSize(size);
      doc.setFont('helvetica', o?.bold ? 'bold' : o?.italic ? 'italic' : 'normal');
      doc.setTextColor(...(o?.color ?? C.dark));
      const lines = doc.splitTextToSize(ascii(t), width) as string[];
      const lh = size * 0.42;
      for (const line of lines) {
        kit.ensure(lh + 1);
        doc.text(line, M + indent, kit.y);
        kit.y += lh;
      }
      kit.y += 1.2;
    },
    row(label, value, o) {
      kit.ensure(7);
      if (o?.tint) {
        doc.setFillColor(...C.cream);
        doc.rect(M - 1, kit.y - 4, W - 2 * M + 2, 6, 'F');
      }
      doc.setFontSize(9);
      doc.setFont('helvetica', o?.bold ? 'bold' : 'normal');
      doc.setTextColor(...(o?.bold ? C.dark : C.gray));
      doc.text(ascii(label), M, kit.y);
      if (o?.note) {
        const lw = doc.getTextWidth(ascii(label));
        doc.setFontSize(7.5);
        doc.setFont('helvetica', 'italic');
        doc.setTextColor(...C.gray);
        const room = W - 2 * M - lw - 48;
        const note = (doc.splitTextToSize(ascii(o.note), Math.max(20, room)) as string[])[0] ?? '';
        doc.text(note, M + lw + 3, kit.y);
        doc.setFontSize(9);
        doc.setFont('helvetica', o?.bold ? 'bold' : 'normal');
      }
      doc.setTextColor(...(o?.valueColor ?? C.dark));
      doc.text(ascii(value), W - M, kit.y, { align: 'right' });
      kit.y += 6;
    },
    table(o) {
      const size = o.size ?? 8;
      const usable = W - 2 * M;
      const xs: number[] = [];
      let acc = M;
      for (const w of o.widths) {
        xs.push(acc);
        acc += w * usable;
      }
      const alignOf = (c: number) => o.align?.[c] ?? (c === 0 ? 'left' : 'right');
      const xFor = (c: number) => {
        const w = o.widths[c] * usable;
        const a = alignOf(c);
        return a === 'left' ? xs[c] : a === 'right' ? xs[c] + w - 1 : xs[c] + w / 2;
      };
      const lh = size * 0.42;
      const drawHead = () => {
        kit.ensure(12);
        doc.setFontSize(size - 0.5);
        doc.setFont('helvetica', 'bold');
        doc.setTextColor(...C.goldDark);
        let maxLines = 1;
        o.head.forEach((h, c) => {
          const lines = doc.splitTextToSize(ascii(h).toUpperCase(), o.widths[c] * usable - 2) as string[];
          maxLines = Math.max(maxLines, lines.length);
          doc.text(lines, xFor(c), kit.y, { align: alignOf(c) });
        });
        kit.y += maxLines * lh + 0.8;
        doc.setDrawColor(...C.gold);
        doc.setLineWidth(0.25);
        doc.line(M, kit.y - 2.2, W - M, kit.y - 2.2);
        kit.y += 1.6;
      };
      drawHead();
      o.rows.forEach((r, ri) => {
        doc.setFontSize(size);
        const cells = r.map((cell, c) => doc.splitTextToSize(ascii(cell), o.widths[c] * usable - 2) as string[]);
        const lines = Math.max(1, ...cells.map((l) => l.length));
        const hgt = lines * lh + 2.2;
        if (kit.y + hgt > H - 16) {
          kit.newPage();
          drawHead();
        }
        if (ri % 2 === 1) {
          doc.setFillColor(...C.cream);
          doc.rect(M - 1, kit.y - lh, usable + 2, hgt, 'F');
        }
        cells.forEach((l, c) => {
          const bold = o.boldRows?.includes(ri) || o.boldCell?.(ri, c);
          doc.setFont('helvetica', bold ? 'bold' : 'normal');
          doc.setTextColor(...(o.cellColor?.(ri, c) ?? (c === 0 ? C.gray : C.dark)));
          doc.text(l, xFor(c), kit.y, { align: alignOf(c) });
        });
        kit.y += hgt;
      });
      kit.y += 2;
    },
    finish(footerLeft) {
      const total = doc.getNumberOfPages();
      for (let i = 1; i <= total; i++) {
        doc.setPage(i);
        doc.setFontSize(7);
        doc.setTextColor(...C.gray);
        doc.setFont('helvetica', 'normal');
        doc.text(ascii(footerLeft), M, H - 8);
        doc.text(`${i} / ${total}`, W - M, H - 8, { align: 'right' });
      }
    },
  };
  return kit;
}

/** "AED 12,345,678" — exact, for report tables. */
export function pdfAed(n: number | null | undefined): string {
  if (n == null || !Number.isFinite(n)) return '-';
  return `${n < 0 ? '-' : ''}AED ${Math.round(Math.abs(n)).toLocaleString('en-US')}`;
}
export function pdfPct(n: number | null | undefined, d = 1): string {
  return n == null || !Number.isFinite(n) ? '-' : `${n.toFixed(d)}%`;
}
export function pdfInt(n: number | null | undefined): string {
  return n == null || !Number.isFinite(n) ? '-' : Math.round(n).toLocaleString('en-US');
}
